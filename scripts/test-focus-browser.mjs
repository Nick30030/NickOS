import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const base = process.env.FOCUS_GUARD_BASE_URL || 'http://127.0.0.1:3002';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(base).hostname), 'Run against an isolated local test server only.');
const results=[];
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE || undefined,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 try {
 const ctx=await browser.newContext();
 const saved={enabled:true,mode:'whitelist',allowedDomains:['github.com'],blockedDomains:['example.com'],blockedApps:[],unknownSitePolicy:'block'};
 await ctx.addInitScript(settings=>{if(!localStorage.getItem('nick_os_focus_guard_settings'))localStorage.setItem('nick_os_focus_guard_settings',JSON.stringify(settings));},saved);
 const page=await ctx.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 await page.getByRole('button',{name:'Démarrer le Focus',exact:true}).first().waitFor();
 await page.waitForTimeout(1000);
 let state=await (await fetch(base+'/api/focus-guard/active-session')).json();
 assert.equal(state.settings.mode,'whitelist');
 results.push('PASS: persisted whitelist settings synchronized on application startup.');
 await page.getByRole('button',{name:'Démarrer le Focus',exact:true}).first().click();
 await page.getByRole('button',{name:'Pause Timer',exact:true}).waitFor();
 await page.waitForTimeout(500);
 state=await (await fetch(base+'/api/focus-guard/active-session')).json();
 assert.equal(state.sessionState,'active');assert.equal(state.isProtectionActive,true);
 const sessionId=state.sessionId;
 results.push('PASS: top Start Focus button creates a real active session in one click.');
 const emptyCtx=await browser.newContext();const empty=await emptyCtx.newPage();
 await empty.goto(base);await empty.getByRole('button',{name:'Démarrer le Focus',exact:true}).first().waitFor();
 await empty.waitForTimeout(1000);
 state=await (await fetch(base+'/api/focus-guard/active-session')).json();
 assert.equal(state.sessionId,sessionId);assert.equal(state.sessionState,'active');assert.equal(state.settings.mode,'whitelist');
 results.push('PASS: an idle second profile cannot erase the active session or its settings.');
 await emptyCtx.close();
 await page.getByRole('button',{name:'Pause Timer',exact:true}).click();await page.waitForTimeout(600);
 state=await (await fetch(base+'/api/focus-guard/active-session')).json();assert.equal(state.sessionState,'paused');assert.equal(state.isProtectionActive,false);
 await page.getByRole('button',{name:'Resume Focus',exact:true}).click();await page.waitForTimeout(600);
 state=await (await fetch(base+'/api/focus-guard/active-session')).json();assert.equal(state.sessionState,'active');assert.equal(state.isProtectionActive,true);
 results.push('PASS: pausing disarms protection and resuming arms it again.');
 await page.getByRole('button',{name:'Complete Task',exact:true}).last().click();await page.waitForTimeout(600);
 state=await (await fetch(base+'/api/focus-guard/active-session')).json();
 assert.equal(state.sessionState,'completed');assert.equal(state.isProtectionActive,false);
 results.push('PASS: completing a task disables protection for its session.');
 await page.getByRole('button',{name:'Exit Focus',exact:true}).click();
 await page.getByRole('button',{name:'Démarrer le Focus',exact:true}).first().click();
 await page.getByRole('button',{name:'Pause Timer',exact:true}).waitFor();await page.waitForTimeout(600);
 state=await (await fetch(base+'/api/focus-guard/active-session')).json();
 assert.equal(state.sessionState,'active');
 const restartedSessionId=state.sessionId;
 await page.reload();await page.getByRole('button',{name:'Démarrer le Focus',exact:true}).first().waitFor();await page.waitForTimeout(600);
 state=await (await fetch(base+'/api/focus-guard/active-session')).json();assert.equal(state.sessionId,restartedSessionId);assert.equal(state.isProtectionActive,true);
 results.push('PASS: page reload restores the real session and its settings.');
 await fetch(base+'/api/focus-guard/heartbeat',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({clientId:'browser-regression-agent',clientType:'browser_extension',status:'enforcing',activeSessionId:restartedSessionId})});
 await page.getByText('Outils / Réglages',{exact:true}).click();
 await page.getByRole('button',{name:/Agents & Diagnostics/}).click();
 await page.getByText('browser-regression-agent',{exact:true}).waitFor();
 results.push('PASS: agent diagnostics display the heartbeat received by the server.');
 assert.equal(errors.length,0,JSON.stringify(errors));
 results.push('PASS: no uncaught browser JavaScript errors during the tested workflow.');
 console.log(results.join('\n'));
 await ctx.close();
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
